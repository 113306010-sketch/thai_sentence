// 新增題目：在對應頁面加一行 s(單字, 聲調, 中文)。
//  - 單字之間用「|」分隔，同一個單字內的音節用「·」分隔
//  - 聲調與音節一一對應：「|」分隔單字，單字內的音節聲調用空白分隔
//  - 第四個參數 note 選填：發音提示，會在第二步顯示；用 {{ }} 包起來的字會標成紅色
//  - 聲調符號：-（平聲） ˇ（低聲） ˊ（上揚聲） ~（高聲）

export const TONE_SYMBOLS = ['-', 'ˇ', 'ˊ', '~'];

function parse(id, wordsStr, tonesStr, zh, note) {
  const words = wordsStr.split('|').map((w) => w.trim());
  const tones = tonesStr.split('|').map((t) => t.trim().split(/\s+/));
  if (words.length !== tones.length) {
    throw new Error(`[data] ${id}: 單字數(${words.length})與聲調組數(${tones.length})不符`);
  }
  const parsed = words.map((w, i) => {
    const syls = w.split('·');
    if (syls.length !== tones[i].length) {
      throw new Error(`[data] ${id}: 「${w}」有 ${syls.length} 個音節，但聲調有 ${tones[i].length} 個`);
    }
    tones[i].forEach((t) => {
      if (!TONE_SYMBOLS.includes(t)) throw new Error(`[data] ${id}: 未知聲調符號「${t}」`);
    });
    return { text: syls.join(''), syls: syls.map((text, k) => ({ text, tone: tones[i][k] })) };
  });
  return {
    id,
    zh,
    note: note || '',
    words: parsed,
    syls: parsed.flatMap((w) => w.syls),
    thai: parsed.map((w) => w.text).join(''),
    splitStr: words.join(' | '),
    toneStr: tones.map((t) => t.join(' ')).join(' | '),
  };
}

function page(n, rows) {
  return rows.map(([w, t, zh, note], i) => parse(`${n}-${i + 1}`, w, t, zh, note));
}
const s = (w, t, zh, note) => [w, t, zh, note];

